// Real-history study: how often did two branches change the SAME function while Git merged them
// without any conflict, and were those merges followed by bug fixes more often than others?
//
//   npm run build -w preflux
//   node packages/cli/dist/merge-study.js services/ml/data/repos/koa services/ml/data/repos/express ...
//
// Writes docs/merge-study.md (and prints a summary). Uses the exact conflict engine Preflux runs
// on every push (src/conflicts), on merges that really happened.

import { writeFileSync } from "node:fs";
import { basename, resolve } from "node:path";
import { FIX_REGEX } from "@preflux/shared/ml";
import { analyseCommits } from "../src/conflicts/analyze.js";
import { languageFor } from "../src/conflicts/parser.js";
import { git, tryGit } from "../src/git/exec.js";

const MAX_MERGES_PER_REPO = Number(process.env.STUDY_MAX_MERGES ?? 400);
const FOLLOW_UP_DAYS = 30;

interface Example {
  repo: string;
  merge: string;
  file: string;
  message: string;
}

interface RepoResult {
  repo: string;
  merges: number;
  /** Merges where both sides changed at least one common JS/TS/Python file. */
  overlapping: number;
  /** ...of which Git reported no text conflict in that file but the same function was edited on both sides. */
  silentSameFunction: number;
  /** ...where one side changed/removed a function's API and the other added calls to it. */
  apiClash: number;
  /** Follow-up fix within FOLLOW_UP_DAYS on a file involved, for silent-clash merges vs other overlapping merges. */
  fixAfterSilent: number;
  fixAfterOther: number;
  otherOverlapping: number;
  examples: Example[];
}

const lines = (s: string) => s.split("\n").map((l) => l.trim()).filter(Boolean);

function changedCode(base: string, tip: string, cwd: string): Set<string> {
  return new Set(lines(git(["diff", "--name-only", "--no-renames", base, tip], cwd)).filter((p) => languageFor(p)));
}

/** Was any of these files touched by a bug-fix commit within FOLLOW_UP_DAYS after the merge? */
function fixedSoon(files: string[], mergeTime: number, branch: string, cwd: string): boolean {
  const until = mergeTime + FOLLOW_UP_DAYS * 86_400;
  const out = git(["log", "--no-merges", "--format=%s", `--since=${mergeTime + 1}`, `--until=${until}`, branch, "--", ...files], cwd);
  return lines(out).some((subject) => FIX_REGEX.test(subject));
}

async function studyRepo(path: string): Promise<RepoResult> {
  const repo = basename(path);
  const branch = git(["rev-parse", "--abbrev-ref", "HEAD"], path).trim();
  const merges = lines(git(["log", "--merges", "--format=%H %P %ct", branch], path))
    .map((l) => l.split(" "))
    .filter((p) => p.length === 4) // exactly two parents
    .slice(0, MAX_MERGES_PER_REPO);

  const r: RepoResult = { repo, merges: merges.length, overlapping: 0, silentSameFunction: 0, apiClash: 0, fixAfterSilent: 0, fixAfterOther: 0, otherOverlapping: 0, examples: [] };
  for (const [sha, p1, p2, ct] of merges as Array<[string, string, string, string]>) {
    const base = tryGit(["merge-base", p1, p2], path)?.trim();
    if (!base || base === p1 || base === p2) continue;
    const ours = changedCode(base, p1, path);
    const shared = [...changedCode(base, p2, path)].filter((f) => ours.has(f));
    if (shared.length === 0) continue;
    r.overlapping++;

    const findings = await analyseCommits(p1, p2, "the other branch", path);
    const silent = findings.filter((f) => f.ruleId === "conflict-same-function" && f.severity === "high");
    const api = findings.filter((f) => f.ruleId === "conflict-changed-api");
    if (api.length > 0) r.apiClash++;

    if (silent.length > 0) {
      r.silentSameFunction++;
      if (fixedSoon([...new Set(silent.map((f) => f.file))], Number(ct), branch, path)) r.fixAfterSilent++;
      if (r.examples.length < 3) r.examples.push({ repo, merge: sha.slice(0, 7), file: silent[0]!.file, message: silent[0]!.message.split(" was also edited")[0]! });
    } else {
      r.otherOverlapping++;
      if (fixedSoon(shared, Number(ct), branch, path)) r.fixAfterOther++;
    }
  }
  return r;
}

const pct = (a: number, b: number) => (b === 0 ? "–" : `${((100 * a) / b).toFixed(1)}%`);

function report(results: RepoResult[]): string {
  const sum = (k: keyof RepoResult) => results.reduce((s, r) => s + (r[k] as number), 0);
  const total = {
    merges: sum("merges"),
    overlapping: sum("overlapping"),
    silent: sum("silentSameFunction"),
    api: sum("apiClash"),
    fixSilent: sum("fixAfterSilent"),
    fixOther: sum("fixAfterOther"),
    other: sum("otherOverlapping"),
  };
  return [
    "# Merge study: conflicts Git doesn't see",
    "",
    `Generated by \`packages/cli/scripts/merge-study.ts\` on ${new Date().toISOString().slice(0, 10)}, using the same conflict engine Preflux runs on every push.`,
    `For each real two-parent merge (up to ${MAX_MERGES_PER_REPO} most recent per repository), both parents were compared against their merge base.`,
    "",
    "| Repository | Merges | Both sides changed a common code file | Same function edited on both sides, merged silently by Git | API changed vs. new calls | Fix within 30 days: silent same-function | Fix within 30 days: other overlapping |",
    "|---|---|---|---|---|---|---|",
    ...results.map((r) => `| ${r.repo} | ${r.merges} | ${r.overlapping} | ${r.silentSameFunction} (${pct(r.silentSameFunction, r.overlapping)}) | ${r.apiClash} | ${pct(r.fixAfterSilent, r.silentSameFunction)} | ${pct(r.fixAfterOther, r.otherOverlapping)} |`),
    `| **Total** | **${total.merges}** | **${total.overlapping}** | **${total.silent} (${pct(total.silent, total.overlapping)})** | **${total.api}** | **${pct(total.fixSilent, total.silent)}** | **${pct(total.fixOther, total.other)}** |`,
    "",
    "## What this shows",
    "",
    `- In **${pct(total.silent, total.overlapping)}** of merges where both branches touched the same code file, both branches edited the **same function**, and Git reported **no conflict**. These are exactly the cases Preflux flags as \`conflict-same-function\` (high).`,
    `- After such silent same-function merges, a bug-fix commit touched one of those files within ${FOLLOW_UP_DAYS} days in **${pct(total.fixSilent, total.silent)}** of cases, compared with **${pct(total.fixOther, total.other)}** for other overlapping merges.`,
    total.silent > 0 && total.other > 0 && total.fixSilent / total.silent > total.fixOther / total.other
      ? "  So in this data, silent same-function merges were followed by bug fixes more often."
      : "  So this data does **not** show that silent same-function merges lead to more bug fixes. Preflux therefore presents them as a **coordination** signal (\"someone else is changing this function\"), not as a bug prediction.",
    "",
    "## Examples",
    "",
    ...results.flatMap((r) => r.examples).slice(0, 8).map((e) => `- ${e.repo} merge \`${e.merge}\`: ${e.message} (\`${e.file}\`)`),
    "",
    "## Limits",
    "",
    "- \"Fix within 30 days\" uses the commit-message fix regex (as SZZ does): it shows correlation, not proof that the merge caused the bug.",
    "- Only merge commits are visible. Squash and rebase merges leave no two-parent commit, so these numbers undercount how often parallel edits happen.",
    "- Function matching is by name per file; see docs/conflicts.md.",
    "- \"API changed vs. new calls\" matches calls by function name and isn't checked by hand; some may be unrelated functions with the same name.",
    "- The silent same-function sample is small, so the follow-up-fix percentages are noisy.",
    "",
  ].join("\n");
}

async function main() {
  const repos = process.argv.slice(2).map((p) => resolve(p));
  if (repos.length === 0) {
    console.error("usage: node dist/merge-study.js <repo path> [...]");
    process.exit(2);
  }
  const results: RepoResult[] = [];
  for (const path of repos) {
    const started = Date.now();
    const r = await studyRepo(path);
    results.push(r);
    console.log(`${r.repo}: ${r.merges} merges, ${r.overlapping} overlapping, ${r.silentSameFunction} silent same-function, ${r.apiClash} API clashes (${Math.round((Date.now() - started) / 1000)}s)`);
  }
  const out = resolve(process.env.STUDY_OUT ?? "docs/merge-study.md");
  writeFileSync(out, report(results));
  console.log(`wrote ${out}`);
}

await main();
